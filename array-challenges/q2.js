// Array Challenge Q2 - Accessing specific element by index
// Objective: Access the third element (index 2) from an array

// Declare an array named 'cities' containing city names
let cities = ["london","newyork","paris","tokyo"]

// Access the third element using index 2
// Index positions: 0='london', 1='newyork', 2='paris', 3='tokyo'
let favouriteCity = cities[2]  // Gets "paris"

// Output the favorite city
console.log(favouriteCity)  // Output: paris