// Array Challenge Q1 - Accessing first element of an array
// Objective: Create an array and access its first element by index

// Declare an array named 'teaFlavours' containing tea names
// Arrays use square brackets [] and store multiple values in order
let teaFlavours = ["green tea", "orange tea", "black tea"]

// Access the first element using index 0 (arrays are 0-indexed in JavaScript)
// Index 0 refers to the first element, index 1 to the second, etc.
let firstTea = teaFlavours[0]  // Gets "green tea"

// Output the first tea flavor
console.log(firstTea)  // Output: green tea