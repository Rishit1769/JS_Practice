// Array Challenge Q9 - Getting Array Length
// Objective: Determine the number of elements in an array

// Create a tea menu array with 5 items
let teaMenu = ["oolong tea","orange tea","green tea","earl tea","masala tea"]

// length property returns the number of elements in the array
// This property is read-only and automatically updates when elements are added/removed
let menuLength = teaMenu.length  // Returns 5

// Output the length
console.log(menuLength)  // Output: 5