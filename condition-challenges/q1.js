// Condition Challenge Q1 - Comparing Numbers
// Objective: Compare two numbers and check if one is greater than the other

// Declare first number
let num1=10;
// Declare second number
let num2=20;

// if-else statement: Makes a decision based on a condition
// Condition: Check if num1 is greater than num2
if(num1>num2){
    // This block executes if num1 > num2 is TRUE
    console.log(num1+" is greater than "+num2);
}
else{
    // This block executes if num1 > num2 is FALSE (i.e., num1 <= num2)
    console.log(num1+" is not greater than "+num2);
    // Output: 10 is not greater than 20
}