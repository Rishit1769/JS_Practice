// Condition Challenge Q5 - Checking Array Length
// Objective: Determine if an array is empty or contains elements

// Declare an empty array
let arr = []

// if-else statement: Check if array is empty
// length property: Returns the number of elements in an array
// arr.length === 0 means the array has no elements
if(arr.length === 0){
    // This block executes if array has NO elements
    console.log("It is empty")
    // Output: It is empty
} else {
    // This block executes if array HAS elements
    console.log("It is not empty")
}